"""Export the launcher SVG as Android vectors and web/store PNGs.

Run from the repository root. Requires ImageMagick. Generated concept art is
kept separately; the SVG is the canonical, editable product icon.

The SVG's visible paths form the full-color mark. Its hidden path with
id="monochrome" is the themed-icon silhouette. Gradients must use
gradientUnits="userSpaceOnUse" so their coordinates carry over unchanged.
"""
from pathlib import Path
import subprocess
import xml.etree.ElementTree as ET

ANDROID = 'http://schemas.android.com/apk/res/android'
AAPT = 'http://schemas.android.com/aapt'
SVG = 'http://www.w3.org/2000/svg'
ET.register_namespace('', SVG)
SOURCE = Path('image/brand/r4l-launcher-mark.svg')
root = ET.parse(SOURCE).getroot()
paths = root.findall(f'{{{SVG}}}path')
color_paths = [p for p in paths if p.get('id') != 'monochrome']
monochrome_paths = [p for p in paths if p.get('id') == 'monochrome'] or color_paths
gradients = {g.get('id'): g for g in root.iter(f'{{{SVG}}}linearGradient')}

# Adaptive background: a soft glow near the top fading to charcoal. These are the release
# colors; res/values/ic_launcher.xml must match them (debug builds override that file).
BG_GLOW, BG_EDGE = '#2A2F45', '#181C24'
BG_GRADIENT = dict(centerX='54', centerY='32.4', gradientRadius='86.4')
CIRCLE = 'M54,0 A54,54 0,1 1,54,108 A54,54 0,1 1,54,0 Z'
SQUARE = 'M0,0 H108 V108 H0 Z'
HEADER = ('<?xml version="1.0" encoding="utf-8"?>\n'
          '<!-- Generated by tools/export-r4l-brand.py from image/brand/r4l-launcher-mark.svg -->\n'
          f'<vector xmlns:android="{ANDROID}" xmlns:aapt="{AAPT}" '
          'android:width="108dp" android:height="108dp" '
          'android:viewportWidth="108" android:viewportHeight="108">\n')


def linear_gradient(gradient_id):
    gradient = gradients[gradient_id]
    items = ''.join(f'<item android:offset="{stop.get("offset")}" '
                    f'android:color="{stop.get("stop-color")}"/>'
                    for stop in gradient.iter(f'{{{SVG}}}stop'))
    return ('<aapt:attr name="android:fillColor"><gradient android:type="linear" '
            f'android:startX="{gradient.get("x1")}" android:startY="{gradient.get("y1")}" '
            f'android:endX="{gradient.get("x2")}" android:endY="{gradient.get("y2")}">'
            f'{items}</gradient></aapt:attr>')


def background_path(path_data):
    attributes = ' '.join(f'android:{k}="{v}"' for k, v in BG_GRADIENT.items())
    return (f'<path android:pathData="{path_data}"><aapt:attr name="android:fillColor">'
            f'<gradient android:type="radial" {attributes}>'
            '<item android:offset="0" android:color="@color/ic_launcher_background_glow"/>'
            '<item android:offset="1" android:color="@color/ic_launcher_background"/>'
            '</gradient></aapt:attr></path>')


def vector_path(path, monochrome):
    values = [f'android:pathData="{path.get("d")}"']
    if path.get('fill-rule') == 'evenodd':
        values.append('android:fillType="evenOdd"')
    fill = path.get('fill', '#000000')
    if monochrome:
        return '<path ' + ' '.join(values + ['android:fillColor="#000000"']) + '/>'
    if fill.startswith('url(#'):
        return '<path ' + ' '.join(values) + '>' + linear_gradient(fill[5:-1]) + '</path>'
    return '<path ' + ' '.join(values + [f'android:fillColor="{fill}"']) + '/>'


def vector(monochrome=False, legacy=False):
    # 0.62 keeps the badge's rounded corners inside the 66 dp adaptive-icon safe circle.
    scale, offset = (0.84, 13.68) if legacy else (0.62, 24.24)
    content = [background_path(CIRCLE)] if legacy else []
    content.append(f'<group android:scaleX="{scale}" android:scaleY="{scale}" '
                   f'android:translateX="{offset}" android:translateY="{offset}">')
    content += [vector_path(p, monochrome) for p in (monochrome_paths if monochrome else color_paths)]
    content.append('</group>')
    return HEADER + '\n'.join(content) + '\n</vector>\n'


for variant in ('foreground', 'monochrome', 'legacy'):
    Path(f'res/drawable/ic_launcher_{variant}.xml').write_text(
        vector(monochrome=variant == 'monochrome', legacy=variant == 'legacy'))
Path('res/drawable/ic_launcher_background.xml').write_text(
    HEADER + background_path(SQUARE) + '\n</vector>\n')

for element in [*color_paths, *gradients.values()]:
    element.tail = None
svg_defs = ''.join(ET.tostring(g, encoding='unicode') for g in gradients.values())
svg_paths = ''.join(ET.tostring(p, encoding='unicode') for p in color_paths)
cx, cy, radius = (float(BG_GRADIENT[k]) for k in ('centerX', 'centerY', 'gradientRadius'))
icon = ('<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 108 108"><defs>'
        f'<radialGradient id="bg" gradientUnits="userSpaceOnUse" cx="{cx:g}" cy="{cy:g}" r="{radius:g}">'
        f'<stop offset="0" stop-color="{BG_GLOW}"/><stop offset="1" stop-color="{BG_EDGE}"/>'
        f'</radialGradient>{svg_defs}</defs>'
        '<rect width="108" height="108" rx="24" fill="url(#bg)"/>'
        f'<g transform="translate(13.68 13.68) scale(.84)">{svg_paths}</g></svg>\n')
freeform = (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 96 96"><defs>{svg_defs}</defs>'
            f'{svg_paths}</svg>\n')
for folder, names, artwork in (
    ('image/app_icon', ('icon.svg', 'icon_browser_fullsize.svg'), icon),
    ('image/app_icon', ('icon_freeform.svg', 'foreground_57pt.svg'), freeform),
    ('docs/assets/img', ('icon_adaptive_baked.svg', 'icon_adaptive_glow.svg'), icon),
    ('docs/assets/img', ('icon_freeform_baked.svg', 'icon_freeform_glow.svg'), freeform),
):
    for name in names:
        Path(folder, name).write_text(artwork)
for target, source in (
    ('ic_default_foreground.xml', 'ic_launcher_foreground.xml'),
    ('ic_default_background.xml', 'ic_launcher_background.xml'),
    ('background_gradient_native.xml', 'ic_launcher_background.xml'),
    ('background_gradient_overscan.xml', 'ic_launcher_background.xml'),
):
    Path('image/app_icon', target).write_text(Path('res/drawable', source).read_text())
for source, target, size in (
    ('image/app_icon/icon_freeform.svg', 'image/brand/r4l-launcher-logo.png', '1024x1024'),
    ('image/app_icon/icon.svg', 'ic_launcher-playstore.png', '512x512'),
    ('image/app_icon/icon.svg', 'fastlane/metadata/android/en-US/images/icon.png', '512x512'),
):
    subprocess.run(['magick', '-background', 'none', '-density', '1536', str(source), '-resize', size, '-depth', '8', 'PNG32:' + target], check=True)
print('Exported launcher SVG, Android vectors, and PNG icons.')
